//! 型レベルスタックマシン。
//!
//! 型レベル計算を命令セット（opcode）で表現し、純粋な小ステップ実行意味論と
//! エフェクト付き実行ループ（モナド変換子スタック）により実行ピックアップ。
//!
//! ## 構成
//!
//! - **opcode**: 命令定義（OpPush、OpAdd、OpIf、OpWhile等）
//! - **vm**: 実行エンジン
//!   - `semantics/`: 純粋な状態遷移関数
//!   - `runtime/`: ランタイムループとエフェクト処理
//!
//! ## 利用フロー
//!
//! 1. Opcode列（命令）からプログラム構築
//! 2. run* 関数でスタックマシンを実行
//! 3. 計算結果を型として取得

