//! 型レベル高階関数と関数型プログラミング。
//!
//! ラムダ計算ベースの型レベル関数抽象化。基本トレイト λ を通じて
//! カリー化と適用を型レベルで実装し、関数型を一級値として扱う基盤。

/// 型レベル高階関数の抽象トレイト。
///
/// 型パラメータ `x` 一つを受け取り、型メンバ `M` を計算する型レベル関数を表す。
/// ラムダ計算での λx.M に対応し、複数引数はカリー化により実装可能。
///
/// # 使用例
///
/// ```text
/// // 型レベル関数：恒等関数 (identity)
/// impl<X> lambda x { type M = X; }
/// ```
trait λ<x> {
    /// 関数が `x` に適用された時の計算結果型。
    type M;
}
